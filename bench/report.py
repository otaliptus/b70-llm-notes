#!/usr/bin/env python3
"""Build results/report.md from every results/*.json: scenario matrix, per-task grid, internal (same-model)
comparisons, conversation / repair / long-context tables, and a noise estimate from the repeated run."""
import glob, json, os, statistics as st
import tasks as T, convo_tasks as C

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
runs = {}
for p in sorted(glob.glob(os.path.join(D, "*.json"))):
    n = os.path.basename(p)[:-5]
    try: runs[n] = json.load(open(p))
    except Exception: pass
rows = lambda r: {k: v for k, v in r.items() if not k.startswith("_")}
kind = lambda n, r: (r.get("_meta") or {}).get("suite") or ("convo" if "turns" in next(iter(rows(r).values()), {}) and "what" in next(iter(rows(r).values()), {}) else "single")
PROFILE = {"fn": "Flash-Next", "sw": "Swift 1.5", "orca": "Orca 27B", "lfm": "LFM2.5-24B-A2B", "bolt": "Nemotron 3.5 Bolt 74B-A9B"}
def label(n):
    p, _, s = n.partition("-")
    return f"{PROFILE.get(p, p)} {s or ('unlim' if p == 'orca' else '')}".strip()
def med(xs):
    xs = [x for x in xs if x is not None]
    return round(st.median(xs), 1) if xs else None
def thinkfail(x): return (not x["verdict"]) and (x.get("finish") == "length" or "no answer" in (x.get("note") or "") or "no code block" in (x.get("note") or ""))
out = []
P = out.append

# ------------------------------------------------------------------ 1. single-turn scenario matrix
single = {n: r for n, r in runs.items() if kind(n, r) == "single"}
P("# Local model bench report\n")
P("Generated by report.py. Scores are tasks passed; `cap` = answers lost because the model was still thinking at the 16k output limit (or produced no code block). Wall = sum over tasks. TTFT = median time to first token; tok/s = median decode rate.\n")
P("## 1. Single-turn scenarios (39 tasks: 24 base + 15 hard)\n")
P("| run | base code | base compr | base know | hard code | hard compr | hard know | total | cap | wall | out tok | med think | ttft | tok/s |")
P("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
def cell(rs):
    return f"{sum(1 for x in rs if x['verdict'])}/{len(rs)}" if rs else "-"
for n, r in single.items():
    rs = rows(r); vals = list(rs.values())
    c = {}
    for tier in ("base", "hard"):
        for cat in ("code", "comprehension", "knowledge"):
            c[tier, cat] = [x for x in vals if x["cat"] == cat and x.get("tier", "base") == tier]
    tot = sum(1 for x in vals if x["verdict"])
    P(f"| {label(n)} | {cell(c['base','code'])} | {cell(c['base','comprehension'])} | {cell(c['base','knowledge'])} | "
      f"{cell(c['hard','code'])} | {cell(c['hard','comprehension'])} | {cell(c['hard','knowledge'])} | **{tot}/{len(vals)}** | "
      f"{sum(1 for x in vals if thinkfail(x))} | {sum(x['wall_s'] or 0 for x in vals)/60:.0f} min | {sum(x['completion_tokens'] or 0 for x in vals)//1000}k | "
      f"{med([x.get('think_tokens_est') for x in vals])} | {med([x.get('ttft_s') for x in vals])} | {med([x.get('decode_tps') for x in vals])} |")
P("")
P("Scenario key: bN = hard thinking budget of N tokens; unlim = no budget; low = soft `reasoning_effort: low`; nothink = thinking off (temp 0.7, top_p 0.8); t06 = temperature 0.6; rep = repeat of b2048 (noise); proj = the engine's shipped control vector enabled (Strata only).\n")

# ------------------------------------------------------------------ 2. per-task grid
P("## 2. Per-task grid (single-turn)\n")
names = list(single)
P("| task | " + " | ".join(label(n) for n in names) + " |")
P("|---|" + "---|" * len(names))
for t in T.ALL:
    cells = []
    for n in names:
        x = rows(single[n]).get(t["id"])
        if not x: cells.append("·"); continue
        mark = "✅" if x["verdict"] else ("⏳" if thinkfail(x) else "❌")
        cells.append(f"{mark} {x['wall_s']:.0f}s" if x["wall_s"] else mark)
    P(f"| {t['id']} ({t['tier'][0]}) | " + " | ".join(cells) + " |")
P("\n✅ pass, ❌ wrong answer, ⏳ ran out of output budget before answering, · not run.\n")

# ------------------------------------------------------------------ 3. internal comparisons
P("## 3. Same-model comparisons\n")
for prof in ("fn", "sw"):
    mine = {n: r for n, r in single.items() if n.startswith(prof + "-")}
    if not mine: continue
    P(f"### {PROFILE[prof]}\n")
    P("| scenario | total | base | hard | code (all) | cap | wall | out tok | passes/min |")
    P("|---|---|---|---|---|---|---|---|---|")
    for n, r in mine.items():
        vals = list(rows(r).values()); tot = sum(1 for x in vals if x["verdict"]); w = sum(x["wall_s"] or 0 for x in vals) / 60
        P(f"| {n[len(prof)+1:]} | {tot}/{len(vals)} | {cell([x for x in vals if x.get('tier','base')=='base'])} | {cell([x for x in vals if x.get('tier')=='hard'])} | "
          f"{cell([x for x in vals if x['cat']=='code'])} | {sum(1 for x in vals if thinkfail(x))} | {w:.0f} min | {sum(x['completion_tokens'] or 0 for x in vals)//1000}k | {tot / w if w else 0:.1f} |")
    a, b = mine.get(f"{prof}-b2048"), mine.get(f"{prof}-b2048-rep")
    if a and b:
        ra, rb = rows(a), rows(b); common = [k for k in ra if k in rb]
        dis = [k for k in common if ra[k]["verdict"] != rb[k]["verdict"]]
        P(f"\nNoise: b2048 vs its repeat disagree on {len(dis)}/{len(common)} tasks ({', '.join(dis) or 'none'}). Differences of that size between any two runs are not meaningful.\n")
    P("")

# ------------------------------------------------------------------ 4. conversations
convo = {n: r for n, r in runs.items() if kind(n, r) == "convo"}
if convo:
    P("## 4. Multi-turn conversations (8 conversations, 24 graded turns, budget 2048)\n")
    P("| conversation | what | " + " | ".join(label(n) for n in convo) + " |")
    P("|---|---|" + "---|" * len(convo))
    for c in C.CONVOS:
        cells = []
        for n in convo:
            x = rows(convo[n]).get(c["id"])
            if not x: cells.append("·"); continue
            marks = "".join("✅" if t["verdict"] else ("➖" if t["verdict"] is None else "❌") for t in x["turns"])
            cells.append(f"{marks} {x['wall_s']:.0f}s")
        P(f"| {c['id']} | {c['what']} | " + " | ".join(cells) + " |")
    P("| **total** | | " + " | ".join(f"**{sum(1 for x in rows(convo[n]).values() if x['verdict'])}/{len(rows(convo[n]))}** conv, "
      f"{sum(x['passed_turns'] for x in rows(convo[n]).values())}/{sum(x['checked_turns'] for x in rows(convo[n]).values())} turns" for n in convo) + " |")
    P("\nOne mark per turn in order.\n")

# ------------------------------------------------------------------ 5. repair loop
rep = {n: r for n, r in runs.items() if kind(n, r) == "repair"}
if rep:
    P("## 5. Repair loop (coding tasks; failed tests are fed back, up to 2 fixes; budget 2048)\n")
    P("| task | " + " | ".join(label(n) for n in rep) + " |")
    P("|---|" + "---|" * len(rep))
    for t in [t for t in T.ALL if t["cat"] == "code"]:
        cells = []
        for n in rep:
            x = rows(rep[n]).get(t["id"])
            if not x: cells.append("·"); continue
            cells.append("".join("✅" if u["verdict"] else "❌" for u in x["turns"]) + f" {x['wall_s']:.0f}s")
        P(f"| {t['id']} ({t['tier'][0]}) | " + " | ".join(cells) + " |")
    P("| **pass@1 / pass@3** | " + " | ".join(f"**{sum(1 for x in rows(rep[n]).values() if x['pass_at_1'])} / {sum(1 for x in rows(rep[n]).values() if x['verdict'])}** of {len(rows(rep[n]))}, "
      f"{sum(x['repairs_used'] for x in rows(rep[n]).values())} repairs, {sum(x['wall_s'] for x in rows(rep[n]).values())/60:.0f} min" for n in rep) + " |")
    P("\nOne mark per attempt: first answer, then each fix after seeing the failing test output.\n")

# ------------------------------------------------------------------ 6. long context
lng = {n: r for n, r in runs.items() if kind(n, r) == "long"}
if lng:
    P("## 6. Long prior conversation (budget 2048)\n")
    P("The task is asked after a synthetic earlier conversation of the given size (doc sections + one-line summaries). Needles are facts planted at 10% / 50% / (15% and 70%) of the way in.\n")
    P("| run | context | score | prompt tok | ttft (cold → warm) | tok/s | per item |")
    P("|---|---|---|---|---|---|---|")
    for n, r in lng.items():
        rs = rows(r)
        for L in sorted({x["target_tokens"] for x in rs.values()}):
            xs = [x for x in rs.values() if x["target_tokens"] == L]
            items = ", ".join(f"{x['item']}{'✅' if x['verdict'] else '❌'}" for x in xs)
            tt = [x["ttft_s"] for x in xs if x["ttft_s"] is not None]
            P(f"| {label(n)} | {L//1000}k | {sum(1 for x in xs if x['verdict'])}/{len(xs)} | {max((x['prompt_tokens'] or 0) for x in xs)} | "
              f"{max(tt) if tt else '-'} → {min(tt) if tt else '-'} s | {med([x['decode_tps'] for x in xs])} | {items} |")
    P("")

open(os.path.join(D, "report.md"), "w").write("\n".join(out))
print("\n".join(out))
